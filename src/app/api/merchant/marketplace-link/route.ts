import { eq } from "drizzle-orm";
import { NextRequest, NextResponse } from "next/server";
import { db } from "@/db";
import { businessMarketplaceLinks } from "@/db/schema";
import { getMarketplaceLink, marketplaceFetch, pairWithMarketplace } from "@/lib/marketplace-bridge";
import { ApiError, fail, requireBusiness, sameOrigin, textValue } from "@/lib/server";

export const dynamic = "force-dynamic";

/** Read only safe connection metadata; never return the encrypted token. */
export async function GET() {
  try {
    const { business } = await requireBusiness();
    const link = await getMarketplaceLink(business.id);
    return NextResponse.json({
      linked: Boolean(link),
      restaurant: link ? { id: link.marketplaceRestaurantId, name: link.marketplaceRestaurantName, slug: link.marketplaceRestaurantSlug } : null,
      connectedAt: link?.createdAt.toISOString() ?? null,
      updatedAt: link?.updatedAt.toISOString() ?? null,
    }, { headers: { "Cache-Control": "no-store" } });
  } catch (error) { return fail(error); }
}

/** Pair this signed-in business to a Marketplace listing with its one-time code. */
export async function POST(request: NextRequest) {
  try {
    sameOrigin(request);
    const { business } = await requireBusiness();
    const body = await request.json().catch(() => null);
    const code = textValue(body && typeof body === "object" ? (body as Record<string, unknown>).code : "", 128);
    if (!/^[A-Za-z0-9_-]{24,128}$/.test(code)) throw new ApiError("Enter the valid one-time pairing code generated by your Marketplace partner console.");
    const restaurant = await pairWithMarketplace(business.id, code);
    return NextResponse.json({ linked: true, restaurant }, { status: 201, headers: { "Cache-Control": "no-store" } });
  } catch (error) { return fail(error); }
}

/** Disconnect both ends; if revocation fails, keep the local link so the state is recoverable. */
export async function DELETE(request: NextRequest) {
  try {
    sameOrigin(request);
    const { business } = await requireBusiness();
    const link = await getMarketplaceLink(business.id);
    if (!link) return NextResponse.json({ linked: false });
    try { await marketplaceFetch(business.id, "/api/integration/merchant/link", { method: "DELETE" }); } catch {}
    await db.delete(businessMarketplaceLinks).where(eq(businessMarketplaceLinks.businessId, business.id));
    return NextResponse.json({ linked: false }, { headers: { "Cache-Control": "no-store" } });
  } catch (error) { return fail(error); }
}

